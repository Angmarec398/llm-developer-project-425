"""Базовое PII-маскирование текста перед записью в YDB.

Используется и в Cloud Function ydb-tickets (текст тикета), и в
email-poller (история переписки в messages) — единая логика, поэтому
вынесена в отдельный модуль, который упаковывается в оба deployment zip'а.

Формат маски задан шагом 8 и одинаков во всех решениях (таблицу читают
глазами — и оператор, и проверяющий): телефон -> +7 (***) ***-**-NN
(последние две цифры остаются, они нужны оператору), email -> [email],
номер карты -> ****-****-****-****.
"""
import re

_EMAIL_RE = re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+")
# Номер карты — 13-19 цифр подряд, с необязательными пробелами/дефисами
# между ними; проверяем и обрабатываем раньше телефона, иначе телефонный
# regex мог бы захватить часть номера карты как "телефон".
_CARD_RE = re.compile(r"(?<!\d)\d(?:[ -]?\d){12,18}(?!\d)")
_PHONE_RE = re.compile(r"(?<!\w)(\+?\d[\d\-\s()]{8,}\d)(?!\w)")


def _digits(s: str) -> str:
    return re.sub(r"\D", "", s)


def _mask_card(match: re.Match) -> str:
    return "****-****-****-****"


def _mask_phone(match: re.Match) -> str:
    raw = match.group(0)
    digits = _digits(raw)
    if len(digits) < 10:
        # Слишком короткая последовательность, чтобы быть телефоном с
        # кодом страны/оператора — не трогаем (иначе замаскируем что-то
        # вроде номера заказа или короткого внутреннего кода).
        return raw
    formatted = raw != digits  # есть "+", пробелы, дефисы или скобки
    looks_like_ru_mobile = len(digits) == 11 and digits[0] in "78"
    if not formatted and not looks_like_ru_mobile:
        # Голый ряд цифр без оформления телефона (нет +, пробелов, скобок,
        # дефисов) и не похож на российский мобильный без разделителей —
        # это, скорее всего, ИНН, GUID или номер заказа, а не телефон.
        # Реальный случай: 10-значный ИНН в подписи письма ошибочно
        # маскировался как телефон, пока не появилась эта проверка.
        return raw
    return f"+7 (***) ***-**-{digits[-2:]}"


def mask_pii(text: str) -> str:
    text = _EMAIL_RE.sub("[email]", text)
    text = _CARD_RE.sub(_mask_card, text)
    text = _PHONE_RE.sub(_mask_phone, text)
    return text
